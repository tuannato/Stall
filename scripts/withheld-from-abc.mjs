#!/usr/bin/env node
/**
 * Regenerate `src/domain/withheld-data.ts` from a Bitcoin ABC checkout.
 *
 * Usage: node scripts/withheld-from-abc.mjs /path/to/bitcoin-abc
 *
 * Reads Cashtab's creation-time name blacklist
 * (`cashtab/src/config/tokenBlacklist.ts` with the fiat table from
 * `cashtab/src/config/CashtabSettings.ts`), Cashtab's offline display
 * blacklist (`cashtab/src/config/token.ts`) and the token-server's seed list
 * (`apps/token-server/src/db.ts`), normalises every name the way Cashtab's
 * `isProbablyNotAScam` does, and writes the module as sorted data. Never run
 * by the suite: a refresh is one command and a diff to read.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const abc = process.argv[2];
if (!abc) {
    console.error('usage: node scripts/withheld-from-abc.mjs <bitcoin-abc checkout>');
    process.exit(2);
}
const read = (p) => readFileSync(join(abc, p), 'utf8');
const strings = (block) => [...block.matchAll(/'((?:[^'\\]|\\.)*)'/g)].map((m) => m[1]);
const normalize = (text) => text.toLowerCase().trim().split(' ').filter((s) => s).join(' ');

const bl = read('cashtab/src/config/tokenBlacklist.ts');
const arr = (key) => {
    const m = bl.match(new RegExp(`^    ${key}: \\[(.*?)^    \\],`, 'ms'));
    if (!m) throw new Error(`no array ${key}`);
    return strings(m[1]);
};
const names = [];
for (const key of [
    'coingeckoTop500Tickers',
    'coingeckoTop500Names',
    'coingeckoTop500Ids',
    'bannedTickers',
    'bannedNames',
]) {
    names.push(...arr(key));
}
const settings = read('cashtab/src/config/CashtabSettings.ts');
for (const m of settings.matchAll(
    /^\s+([a-z]{3}): \{\s*name: '((?:[^'\\]|\\.)*)',\s*symbol: '((?:[^'\\]|\\.)*)'/gm,
)) {
    names.push(m[1], m[2], m[3]);
}
// Stall's own additions: the two Firma currencies Cashtab's list does not
// carry (the owner's rule, 2026-09-05); `firma` and `xecx` are already there.
names.push('fchf', 'feur', 'firma chf', 'firma eur', 'staked xec', 'xecx', 'firma');

const ids = new Map();
const tk = read('cashtab/src/config/token.ts');
for (const id of strings(tk.match(/blacklist: \[(.*?)\],/s)[1])) {
    if (/^[0-9a-f]{64}$/.test(id)) ids.set(id, 'cashtab offline blacklist');
}
const db = read('apps/token-server/src/db.ts');
for (const m of db.matchAll(/tokenId:\s*'([0-9a-f]{64})',\s*reason:\s*'((?:[^'\\]|\\.)*)'/g)) {
    ids.set(m[1], `token-server: ${m[2]}`);
}
// The four the owner named (verified in cashtab/src/constants/tokens.ts,
// cashtab/src/config/app.ts and apps/notifications-server).
for (const [id, why] of [
    ['0387947fd575db4fb19a3e322f635dec37fd192b5941625b66bc4b2c3008cbf0', 'FIRMA (owner rule)'],
    ['a8c83ebe937b9c1b0a7cb7645f43459f57a10043744ddfbc2357e1bd43fe2465', 'Firma CHF (owner rule)'],
    ['cd751e3dfc23da5344bf66cb8433c31464ab4adbdbc9082f22c71bb53eafa7e8', 'Firma EUR (owner rule)'],
    ['c67bf5c2b6d91cfb46a5c1772582eff80d88686887be10aa63b0945479cf4ed4', 'Staked XEC (owner rule)'],
]) {
    ids.set(id, why);
}

const uniqueNames = [...new Set(names.map(normalize).filter((s) => s))].sort();
const sortedIds = [...ids.keys()].sort();
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const out = `// Generated by scripts/withheld-from-abc.mjs from a Bitcoin ABC checkout on
// ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: re-run the script and read the diff.
//
// Names: Cashtab's creation-time blacklist (cashtab/src/config/tokenBlacklist.ts,
// fiat table from cashtab/src/config/CashtabSettings.ts), normalised the way
// Cashtab's isProbablyNotAScam normalises before comparing, plus Stall's own
// four additions. Ids: Cashtab's offline display blacklist
// (cashtab/src/config/token.ts), the token-server's seed list
// (apps/token-server/src/db.ts, reason kept), and the four tokens the owner
// named.

/** Normalised names and tickers this page will not paint a token under. */
export const WITHHELD_NAMES: readonly string[] = [
${uniqueNames.map((n) => `    '${esc(n)}',`).join('\n')}
];

/** Token ids this page will not paint, with why. */
export const WITHHELD_TOKEN_IDS: ReadonlyMap<string, string> = new Map([
${sortedIds.map((id) => `    ['${id}', '${esc(ids.get(id))}'],`).join('\n')}
]);
`;
const target = new URL('../src/domain/withheld-data.ts', import.meta.url);
writeFileSync(target, out);
console.log(`wrote ${uniqueNames.length} names and ${sortedIds.length} ids to src/domain/withheld-data.ts`);
